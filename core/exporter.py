def build_obsidian_markdown(
    report_md: str,
    sources_list: Sequence[SourceDocument],
    metadata: Optional[Dict[str, object]] = None,
) -> str:
    """Format research synthesis for Obsidian PKM vaults with frontmatter and wikilinks."""
    meta = metadata or {}
    topic = meta.get("title") or meta.get("topic") or "OmniResearch Synthesis"
    date_str = meta.get("date") or datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    score = meta.get("groundedness_score", 100)
    sources = collect_bibliography(report_md, sources_list) if report_md else [d for d in sources_list if d.enabled]

    frontmatter = (
        "---\n"
        f'title: "{topic}"\n'
        f'date: "{date_str}"\n'
        f'groundedness_score: "{score}%"\n'
        "tags: [omni-research, synthesis, verified]\n"
        f"sources_count: {len(sources)}\n"
        "---\n\n"
    )

    doc_map = {d.cite_id: d for d in sources}

    def _cite_replacer(match: re.Match) -> str:
        group_str = match.group(1)
        tokens = [t.strip() for t in group_str.split(",") if t.strip()]
        out_tokens = []
        for t in tokens:
            cid_str = t.split(":p.")[0].strip() if ":p." in t else t
            if cid_str.isdigit() and int(cid_str) in doc_map:
                cid = int(cid_str)
                clean_title = re.sub(r"[#*_`\[\]\(\)]", " ", doc_map[cid].title).strip()
                out_tokens.append(f"[[#Source {cid} - {clean_title}|[{t}]]]")
            else:
                out_tokens.append(f"[{t}]")
        return ", ".join(out_tokens)

    transformed_body = re.sub(r"\[([0-9:p\.,\s]+)\]", _cite_replacer, report_md)

    footer_sections = ["\n\n## Sources & References\n"]
    for doc in sources:
        clean_title = re.sub(r"[#*_`\[\]\(\)]", " ", doc.title).strip()
        loc = doc.path_or_uri or "local corpus"
        excerpt = _excerpt(doc, 220)
        footer_sections.append(
            f"### Source {doc.cite_id} - {clean_title}\n"
            f"- **Location/URI:** `{loc}`\n"
            f"- **Type:** `{doc.source_type}`\n"
            f"- **Excerpt:** *{excerpt}*\n"
        )

    return frontmatter + transformed_body.strip() + "\n" + "\n".join(footer_sections)


