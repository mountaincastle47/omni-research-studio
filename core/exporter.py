def build_marp_markdown(
    report_md: str,
    metadata: Optional[Dict[str, object]] = None,
) -> str:
    """Format report into a clean presentation deck using Marp YAML directives."""
    meta = metadata or {}
    title = meta.get("title") or meta.get("topic") or "OmniResearch Executive Briefing"
    date_str = meta.get("date") or datetime.datetime.now().strftime("%Y-%m-%d")

    header = (
        "---\n"
        "marp: true\n"
        "theme: gaia\n"
        "_class: lead\n"
        "paginate: true\n"
        "backgroundColor: #0f172a\n"
        "color: #f1f5f9\n"
        "---\n\n"
        f"# {title}\n\n"
        f"### Grounded Research & Strategic Intelligence\n\n"
        f"**Date:** {date_str}  \n"
        f"**Generated by:** OmniResearch Studio\n\n"
        "---\n\n"
    )

    cleaned = strip_report_header(report_md)
    sections = re.split(r"\n(?=##\s+)", cleaned)

    slides = []
    for sec in sections:
        sec_text = sec.strip()
        if not sec_text:
            continue
        if len(sec_text) > 1200:
            subsections = re.split(r"\n(?=###\s+)", sec_text)
            if len(subsections) > 1:
                slides.extend(sub.strip() for sub in subsections if sub.strip())
                continue
        slides.append(sec_text)

    slide_body = "\n\n---\n\n".join(slides)
    return header + slide_body + "\n"


def export_to_marp(
    filepath: str | Path | None = None,
    report_md: str = "",
    metadata: Optional[Dict[str, object]] = None,
    *,
    output_path: str | Path | None = None,
) -> Path:
    """Save report formatted as presentation slides for Marp preview and slide decks."""
