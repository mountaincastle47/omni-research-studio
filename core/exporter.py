def _label(key: str, language: str) -> str:
    lang = "ko" if str(language).lower().startswith("ko") else "en"
    return _LABELS[key][lang]


def strip_report_header(markdown_text: str) -> str:
    """Remove the in-app `# Grounded Synthesis Report` + meta line + `---` header block (the cover replaces it)."""
    lines = markdown_text.strip().splitlines()
    if not lines or not lines[0].startswith("# "):
        return markdown_text.strip()
    for offset in range(1, min(len(lines), 8)):
        if lines[offset].strip() == "---":
            return "\n".join(lines[offset + 1 :]).strip()
    return "\n".join(lines[1:]).strip()


def source_domain(doc: SourceDocument) -> str:
    """Return a display domain for a document (URL host, or 'local file')."""
    uri = doc.path_or_uri or ""
    if uri.lower().startswith(("http://", "https://")):
        host = urlparse(uri).netloc
        if "vertexaisearch.cloud.google.com" not in host:
            return host.removeprefix("www.")
    for link in doc.metadata.get("grounding_links", []) if isinstance(doc.metadata.get("grounding_links"), list) else []:
        if isinstance(link, dict) and str(link.get("title", "")).strip():
            return str(link["title"]).strip()[:60]
    if uri.startswith("omnisweep://"):
        return "OmniSweep"
    return "local file"


def collect_bibliography(markdown_text: str, documents: Sequence[SourceDocument]) -> List[SourceDocument]:
    """Cited sources in numerical order; when nothing is cited, every enabled source."""
    by_id = {d.cite_id: d for d in documents if d.enabled}
    cited = sorted(n for n in extract_citation_ids(markdown_text) if n in by_id)
    if cited:
        return [by_id[n] for n in cited]
    return [by_id[n] for n in sorted(by_id)]


def _excerpt(doc: SourceDocument, limit: int = 220) -> str:
    cleaned = re.sub(r"\s+", " ", doc.content).strip()
    return cleaned if len(cleaned) <= limit else cleaned[: limit - 1].rstrip() + "…"


def _badge_color(audit: Optional[CitationAudit], score_override: Optional[int] = None) -> str:
    if score_override is not None:
        score = score_override
    elif audit is not None and audit.has_citations:
        score = audit.score
    else:
        score = 100
    return "#1a7f37" if score >= 90 else ("#9a6700" if score >= 60 else "#cf222e")


def _audit_text(audit: Optional[CitationAudit], language: str, score_override: Optional[int] = None) -> str:
    if audit is not None and audit.has_citations:
        return f"{audit.score}% ({audit.valid_citations}/{audit.total_citations} {_label('verified', language)})"
    if score_override is not None:
        return f"{score_override}%"
    return "100%"


